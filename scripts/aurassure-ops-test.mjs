import assert from 'node:assert/strict';
import { localMidnightUnix, parseOptions, buildJobs } from './aurassure-ops.mjs';
const now=1793718000;
assert.equal(localMidnightUnix('2026-10-22'),1792638000);
assert.throws(()=>localMidnightUnix('2026-02-30'));
assert.deepEqual(buildJobs(parseOptions(['stations','--dry-run']),now),[{operation:'stations'}]);
const recent=buildJobs(parseOptions(['recent','--minutes','60','--period','900']),now);
assert.equal(recent[0].from_time,now-3600);
assert.equal(recent[0].upto_time,now);
assert.deepEqual(recent[0].things,[46560,46561,46562]);
const raw=buildJobs(parseOptions(['recent','--raw','--station','46560']),now);
assert.equal(raw[0].data_type,'raw');
assert.equal(raw[0].aggregation_period,undefined);
const days=buildJobs(parseOptions(['backfill','--from','2026-10-22','--to','2026-10-24']),now);
assert.equal(days.length,3);
assert.equal(days[0].from_time,1792638000);
assert.equal(days[0].upto_time,1792724400);
assert.throws(()=>parseOptions(['backfill','--from','2026-10-22']));
assert.throws(()=>parseOptions(['recent','--station','9999']));
assert.throws(()=>buildJobs(parseOptions(['backfill','--from','2026-10-22','--to','2026-11-30']),now));
assert.throws(()=>buildJobs(parseOptions(['backfill','--from','2026-11-03','--to','2026-11-03']),now));
assert.throws(()=>buildJobs(parseOptions(['recent','--minutes','1500']),now));
console.log('Aurassure operator tests passed');
